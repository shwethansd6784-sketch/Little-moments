// Helper to look up a theme by occasion and theme ID
export function getTheme(occasionId, themeId) {
  const occasionThemes = THEMES_BY_OCCASION[occasionId] || THEMES_BY_OCCASION.birthday;
  if (!themeId) return occasionThemes[0];
  const found = occasionThemes.find(t => t.id === themeId);
  return found || occasionThemes[0];
}

// Helper to get all themes for an occasion
export function getThemesForOccasion(occasionId) {
  return THEMES_BY_OCCASION[occasionId] || THEMES_BY_OCCASION.custom;
}
